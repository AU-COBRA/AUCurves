/// Fp inversion via Fermat's little theorem: a^{-1} = a^{p-2} mod p.
/// Uses the verified bls12_mul and bls12_square functions.
fn by_fp_inv(out: u64, x: u64) {
    // p - 2 as 6 x 64-bit words (little-endian)
    const PM2: [u64; 6] = [
        0xb9feffffffffaaa9, 0x1eabfffeb153ffff,
        0x6730d2a0f6b0f624, 0x64774b84f38512bf,
        0x4b1ba7b6434bacd7, 0x1a0111ea397fe69a,
    ];
    // R mod p = Montgomery form of 1
    const R_MOD_P: [u64; 6] = [
        0x760900000002fffd, 0xebf4000bc40c0002,
        0x5f48985753c758ba, 0x77ce585370525745,
        0x5c071a97a256ec6d, 0x15f65ec3fa80e493,
    ];

    let mut result = R_MOD_P;
    let mut base = [0u64; 6];
    unsafe {
        std::ptr::copy_nonoverlapping(x as *const u64, base.as_mut_ptr(), 6);
    }

    for word in (0..6).rev() {
        let w = PM2[word];
        let start_bit = if word == 5 { 60 } else { 63 };
        for bit in (0..=start_bit).rev() {
            bls12_square(result.as_mut_ptr() as u64, result.as_ptr() as u64);
            if (w >> bit) & 1 == 1 {
                bls12_mul(
                    result.as_mut_ptr() as u64,
                    result.as_ptr() as u64,
                    base.as_ptr() as u64,
                );
            }
        }
    }

    unsafe {
        std::ptr::copy_nonoverlapping(result.as_ptr(), out as *mut u64, 6);
    }
}

