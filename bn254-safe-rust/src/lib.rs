#[repr(transparent)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fp(pub [u64; 4]);

#[repr(transparent)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fp2(pub [u64; 8]);

#[repr(transparent)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fp6(pub [u64; 24]);

#[repr(transparent)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fp12(pub [u64; 48]);

macro_rules! impl_field {
    ($name:ident, $n:expr) => {
        impl $name {
            #[inline] pub const fn from_limbs(limbs: [u64; $n]) -> Self { $name(limbs) }
            #[inline] pub const fn zero() -> Self { $name([0u64; $n]) }
            #[inline] pub fn as_limbs(&self) -> &[u64; $n] { &self.0 }
            #[inline] pub fn as_limbs_mut(&mut self) -> &mut [u64; $n] { &mut self.0 }
        }
    }
}

impl_field!(Fp, 4);
impl_field!(Fp2, 8);
impl_field!(Fp6, 24);
impl_field!(Fp12, 48);

