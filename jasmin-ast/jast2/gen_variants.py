#!/usr/bin/env python3
"""Writes variants.h for test_variants.c / bench_variants.c.
usage: gen_variants.py out.h  op:label:symbol ...
  op in add sub mul square; label is the row name; symbol the (renamed) C symbol."""
import sys
out = sys.argv[1]
rows = [a.split(':', 2) for a in sys.argv[2:]]
with open(out, 'w') as f:
    f.write('/* generated by gen_variants.py */\n')
    for op, lab, sym in rows:
        if op == 'square':
            f.write(f'void {sym}(uint64_t *, const uint64_t *);\n')
        else:
            f.write(f'void {sym}(uint64_t *, const uint64_t *, const uint64_t *);\n')
    f.write('static const struct variant VARIANTS[] = {\n')
    for op, lab, sym in rows:
        f.write(f'  {{"{op}", "{lab}", (void (*)(void)){sym}}},\n')
    f.write('};\n#define NVAR (int)(sizeof VARIANTS / sizeof VARIANTS[0])\n')
