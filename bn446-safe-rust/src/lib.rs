//! BN446 pairing — safe Rust tower over verified bedrock2 leaves.
//!
//! 7 limbs (446-bit prime). Curve: BN with seed
//!   u = 0x4000000000000000001000000001 = 2^110 + 2^36 + 1,
//!   E : y^2 = x^3 + 257, Fp2 = Fp[u]/(u^2+1), xi = 1 + 9u,
//!   D-twist E' : y^2 = x^3 + 257/xi
//! (AUCurves Curves/BN446_params.v; checked in PairingTheory/BN446ParamsCheck.v).
//!
//! [pairing] is the emitted optimal-ate pairing tower::bn446_pairing_dsd_optimal
//! (bedrock2 BN446_Pairing.v: D-twist line bn446_make_line_corrected, correction lines
//! through pi(Q) and -pi^2(Q), DSD final exponentiation).

#![allow(non_snake_case, non_camel_case_types)]
