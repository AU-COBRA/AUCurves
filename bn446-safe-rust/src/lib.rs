/// The BN446 optimal-ate pairing e(P, Q), P = (p_x, p_y) in G1, Q = (q_x, q_y) in G2 (Montgomery
/// form): tower::bn446_pairing_dsd_optimal, emitted from bedrock2.  It used to be
/// tower::bn446_pairing_dsd, which is not bilinear (wrong line layout, no correction lines).
pub fn pairing(out: &mut Fp12, p_x: &Fp, p_y: &Fp, q_x: &Fp2, q_y: &Fp2) {
    tower::bn446_pairing_dsd_optimal(out, p_x, p_y, q_x, q_y)
}

/// The optimal-ate Miller loop (with the two correction lines): tower::bn446_miller_loop_optimal.
pub fn miller_loop(out: &mut Fp12, p_x: &Fp, p_y: &Fp, q_x: &Fp2, q_y: &Fp2) {
    tower::bn446_miller_loop_optimal(out, p_x, p_y, q_x, q_y)
}

/// tower::bn446_pairing_dsd as emitted (wrong line layout, no correction lines; not bilinear).
/// Kept for comparison.
pub fn pairing_dsd_uncorrected(out: &mut Fp12, p_x: &Fp, p_y: &Fp, q_x: &Fp2, q_y: &Fp2) {
    tower::bn446_pairing_dsd(out, p_x, p_y, q_x, q_y)
}

/// tower::bn446_miller_loop as emitted (wrong line layout, no correction lines).
pub fn miller_loop_uncorrected(out: &mut Fp12, p_x: &Fp, p_y: &Fp, q_x: &Fp2, q_y: &Fp2) {
    tower::bn446_miller_loop(out, p_x, p_y, q_x, q_y)
}

