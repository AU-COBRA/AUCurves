#!/usr/bin/env python3
"""Turn the Redirect'ed Prints of scripts/GenBLS12LeafBodies.v into BLS12LeafBodies.v."""
import sys
d, out = sys.argv[1], sys.argv[2]
parts = ['''(** * The bedrock2 bodies of fiat-crypto's BLS12-381 Fp add, sub, mul and square.

    Generated by scripts/gen_bls12_leaf_bodies.sh (Print of the vm_compute'd bodies of
    [bls12_add], [bls12_sub], [bls12_mul], [bls12_square] of
    Bedrock.Field.Synthesis.Examples.bls12_prime).  This file depends on bedrock2's syntax only,
    so that it can be loaded next to Jasmin's semantics (which cannot be loaded together with
    fiat-crypto's synthesis pipeline: universe inconsistency through ITree).
    [BLS12LeafSpecsProof.bls12_*_eq] checks these terms against bls12_prime by [vm_compute]. *)
From Stdlib Require Import String ZArith.
Require Import bedrock2.Syntax.
Local Open Scope string_scope.
Local Open Scope Z_scope.
''']
for n in ['add', 'sub', 'mul', 'square']:
    t = open(f'{d}/{n}_body.out').read()
    t = t.split('=', 1)[1].rsplit(':', 1)[0].strip()
    parts.append(f'Definition bls12_{n}_body : cmd :=\n  {t}.\n')
open(out, 'w').write('\n'.join(parts))
