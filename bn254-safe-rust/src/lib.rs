//! BN254 pairing library extracted from verified bedrock2 proofs.
//!
//! The inner unsafe functions are mechanically extracted from the
//! bedrock2 separation-logic-verified implementation via ToRustString.v.
//! The outer safe API uses newtype field types and Rust's borrow checker
//! to enforce the non-aliasing invariants that the bedrock2 WP proofs
//! establish via separating conjunction.
//!
//! No C compiler is needed — this is pure Rust (Path B).

