/// BN254 optimal Ate pairing: out = e(P, Q).
/// P = (p_x, p_y) ∈ G1, Q = (q_x, q_y) ∈ G2.
#[inline]
pub fn pairing(out: &mut Fp12, p_x: &Fp, p_y: &Fp, q_x: &Fp2, q_y: &Fp2) {
    unsafe { inner::bn254_pairing_dsd(
        out.as_limbs_mut().as_mut_ptr() as u64,
        p_x.as_limbs().as_ptr() as u64,
        p_y.as_limbs().as_ptr() as u64,
        q_x.as_limbs().as_ptr() as u64,
        q_y.as_limbs().as_ptr() as u64) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_fp_add_disjoint() {
        let a = Fp::from_limbs([1, 2, 3, 4]);
        let b = Fp::from_limbs([5, 6, 7, 8]);
        let mut c = Fp::zero();
        fp_add(&mut c, &a, &b);
        assert_eq!(c.as_limbs(), &[6, 8, 10, 12]);
    }

    #[test]
    fn test_pairing_runs() {
        let p_x = Fp::from_limbs([1, 0, 0, 0]);
        let p_y = Fp::from_limbs([2, 0, 0, 0]);
        let q_x = Fp2::zero();
        let q_y = Fp2::zero();
        let mut out = Fp12::zero();
        pairing(&mut out, &p_x, &p_y, &q_x, &q_y);
        // Smoke test: output should be non-trivial
        assert_ne!(out.as_limbs()[0], 0);
    }
}
